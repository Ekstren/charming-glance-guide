import assert from 'node:assert/strict';
let config,requests=0;
const oauth={initTokenClient(options){config=options;return {requestAccessToken(options){assert.equal(options.prompt,'select_account');requests++;}};}};
globalThis.window={google:{accounts:{oauth2:oauth}}};
const {prepareGoogleOwnerSignIn}=await import('../src/chat-google-signin.mjs');
await assert.rejects(prepareGoogleOwnerSignIn(''),/not configured/);
const request=await prepareGoogleOwnerSignIn('test.apps.googleusercontent.com');
assert.equal(config.scope,'openid email profile');
assert.equal(config.include_granted_scopes,false);
let token=request();
await assert.rejects(request(),/already in progress/);
assert.equal(requests,1,'one popup for overlapping requests');
config.callback({access_token:'test-token'});
assert.equal(await token,'test-token');
token=request();config.error_callback({type:'popup_closed'});
await assert.rejects(token,/did not finish/);
token=request();config.error_callback({type:'popup_failed_to_open'});
await assert.rejects(token,/blocked/);
token=request();config.callback({error:'access_denied'});
await assert.rejects(token,/not authorized/);
token=request();config.callback({access_token:'retry-token'});
assert.equal(await token,'retry-token','retry succeeds after a canceled popup');
let loads=0;
window.google=undefined;
globalThis.document={createElement(){return {remove(){}};},head:{append(script){loads++;assert.equal(script.src,'https://accounts.google.com/gsi/client');queueMicrotask(()=>{if(loads===1)script.onerror();else{window.google={accounts:{oauth2:oauth}};script.onload();}});}}};
const fresh=await import('../src/chat-google-signin.mjs?loader');
await assert.rejects(fresh.prepareGoogleOwnerSignIn('test.apps.googleusercontent.com'),/could not load/);
await fresh.prepareGoogleOwnerSignIn('test.apps.googleusercontent.com');
assert.equal(loads,2,'failed Google script loading can be retried');
console.log('Google owner sign-in: lazy loader, basic identity scopes, popup cancellation, duplicate guard, and retry passed.');
